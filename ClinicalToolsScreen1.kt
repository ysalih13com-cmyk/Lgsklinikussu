@OptIn(ExperimentalLayoutApi::class)
@Composable
fun QuestionBankScreen(
    repository: LgsRepository,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    var selectedCourseId by remember { mutableStateOf<String?>(null) }
    val filteredQuestions = remember(selectedCourseId) {
        if (selectedCourseId == null) LgsCurriculum.quizQuestions else LgsCurriculum.quizQuestions.filter { it.courseId == selectedCourseId }
    }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Geri")
            }
            Text("📑 Soru Bankası", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
        }

        Spacer(modifier = Modifier.height(6.dp))

        // Subject filter chips
        FlowRow(
            horizontalArrangement = Arrangement.spacedBy(6.dp),
            modifier = Modifier.fillMaxWidth()
        ) {
            FilterChip(
                selected = selectedCourseId == null,
                onClick = { selectedCourseId = null },
                label = { Text("Tümü (${LgsCurriculum.quizQuestions.size})") }
            )
            LgsCurriculum.courses.forEach { c ->
                FilterChip(
                    selected = selectedCourseId == c.id,
                    onClick = { selectedCourseId = c.id },
                    label = { Text("${c.icon} ${c.name}") }
                )
            }
        }

        Spacer(modifier = Modifier.height(10.dp))

        LazyColumn(
            verticalArrangement = Arrangement.spacedBy(12.dp),
            modifier = Modifier.fillMaxSize()
        ) {
            itemsIndexed(filteredQuestions) { index, q ->
                MiniQuizCard(qIndex = index, item = MiniQuizItem(q.question, q.options, q.correctIndex, q.explanation))
            }
        }
    }
}
