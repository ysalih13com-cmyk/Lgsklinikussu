@Composable
fun AiCoachScreen(
    repository: LgsRepository,
    onNavigate: (Screen) -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    var availableMinutes by remember { mutableIntStateOf(60) }
    var planItems by remember { mutableStateOf<List<TodoItem>>(emptyList()) }
    var planGenerated by remember { mutableStateOf(false) }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Geri")
            }
            Text("🤖 AI Çalışma Koçu", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
        }

        Spacer(modifier = Modifier.height(8.dp))
        Text(
            text = "Bugün ne kadar vaktin var? Zayıf konularına, yanlış oranına ve tekrar bekleyen kartlarına göre sana özel bir reçete oluşturalım.",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )

        Spacer(modifier = Modifier.height(14.dp))

        Card(
            shape = RoundedCornerShape(14.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Text("Çalışma Bütçesi Seç:", fontWeight = FontWeight.Bold)
                Spacer(modifier = Modifier.height(8.dp))
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    listOf(30, 45, 60, 90, 120).forEach { mins ->
                        FilterChip(
                            selected = availableMinutes == mins,
                            onClick = { availableMinutes = mins },
                            label = { Text("${mins}dk") }
                        )
                    }
                }
                Spacer(modifier = Modifier.height(12.dp))
                Button(
                    onClick = {
                        planItems = repository.generateCoachSchedule(availableMinutes)
                        planGenerated = true
                    },
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Text("Reçeteyi Hazırla ($availableMinutes dk)")
                }
            }
        }

        Spacer(modifier = Modifier.height(14.dp))

        if (planGenerated) {
            LazyColumn(
                modifier = Modifier.weight(1f),
                verticalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                item {
                    Text(
                        text = "📋 Bugünün Reçetesi (Toplam $availableMinutes dk):",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }

                items(planItems) { item ->
                    Card(
                        shape = RoundedCornerShape(12.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                    ) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(12.dp),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.SpaceBetween
                        ) {
                            Text(item.text, modifier = Modifier.weight(1f), style = MaterialTheme.typography.bodyMedium)
                            Button(
                                onClick = {
                                    when (item.targetTab) {
                                        "srs" -> onNavigate(Screen.SrsSpacedRepetition)
                                        "mistake" -> onNavigate(Screen.MistakeDetective)
                                        "trial" -> onNavigate(Screen.TrialExams)
                                        "bank" -> onNavigate(Screen.QuestionBank)
                                        "pomodoro" -> onNavigate(Screen.Pomodoro)
                                        "video" -> {
                                            if (item.targetCourse != null && item.targetUnit != null) {
                                                onNavigate(Screen.UnitDetail(item.targetCourse, item.targetUnit, "video"))
                                            } else onNavigate(Screen.CurriculumMap)
                                        }
                                        else -> onNavigate(Screen.TodoList)
                                    }
                                },
                                contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 10.dp, vertical = 4.dp),
                                modifier = Modifier.height(32.dp)
                            ) {
                                Text("Git", fontSize = 12.sp)
                            }
                        }
                    }
                }

                item {
                    Spacer(modifier = Modifier.height(6.dp))
                    Button(
                        onClick = {
                            planItems.forEach {
                                repository.addTodo(it.text, it.targetCourse, it.targetUnit, it.targetTab, isAuto = true)
                            }
                            onNavigate(Screen.TodoList)
                        },
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Icon(Icons.Default.Add, contentDescription = null)
                        Spacer(modifier = Modifier.width(6.dp))
                        Text("Tümünü 'Bugün Ne Çalışmalıyım?' Listesine Ekle")
                    }
                }
            }
        }
    }
}

@Composable
fun CurriculumMapScreen(
    repository: LgsRepository,
    onNavigate: (Screen) -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    val unitProgressMap by repository.unitProgressMap.collectAsState()

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Geri")
            }
            Text("🗺️ LGS Konu Haritası", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
        }

        Spacer(modifier = Modifier.height(4.dp))
        Text(
            text = "Tüm LGS müfredatı ve klinik sağlık durumun:",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
        Spacer(modifier = Modifier.height(10.dp))

        LazyColumn(
            verticalArrangement = Arrangement.spacedBy(14.dp),
            modifier = Modifier.fillMaxSize()
        ) {
            LgsCurriculum.courses.forEach { course ->
                item {
                    Text(
                        text = "${course.icon} ${course.name}",
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }

                items(course.units) { unitName ->
                    val key = "${course.id}|$unitName"
                    val prog = unitProgressMap[key]
                    val isDone = prog?.completed == true
                    val accuracy = if (prog != null && prog.totalAnswers >= 3) {
                        (prog.correctAnswers * 100) / prog.totalAnswers
                    } else null

                    val dotColor = when {
                        accuracy == null -> Color.Gray
                        accuracy >= 75 -> SuccessGreen
                        accuracy >= 50 -> Color(0xFFF59E0B)
                        else -> Color(0xFFDC2626)
                    }

                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(12.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                verticalAlignment = Alignment.CenterVertically,
                                horizontalArrangement = Arrangement.SpaceBetween
                            ) {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Box(
                                        modifier = Modifier
                                            .size(10.dp)
                                            .clip(CircleShape)
                                            .background(dotColor)
                                    )
                                    Spacer(modifier = Modifier.width(8.dp))
                                    Text(unitName, fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)
                                }
                                if (isDone) {
                                    Text("✓ Bitti", color = SuccessGreen, fontWeight = FontWeight.Bold, fontSize = 12.sp)
                                }
                            }

                            if (accuracy != null) {
                                Text(
                                    text = "Doğruluk: %$accuracy (${prog?.correctAnswers}/${prog?.totalAnswers})",
                                    fontSize = 11.sp,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                    modifier = Modifier.padding(top = 2.dp)
                                )
                            }

                            Spacer(modifier = Modifier.height(8.dp))

                            // Action buttons
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(6.dp)
                            ) {
                                FilledTonalButton(
                                    onClick = { onNavigate(Screen.UnitDetail(course.id, unitName, "video")) },
                                    modifier = Modifier.weight(1f),
                                    contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 4.dp, vertical = 2.dp)
                                ) {
                                    Text("Öğren", fontSize = 11.sp)
                                }
                                FilledTonalButton(
                                    onClick = { onNavigate(Screen.TeacherRoom(initialTopic = unitName, initialReason = "Konu haritasından seçildi")) },
                                    modifier = Modifier.weight(1f),
                                    contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 4.dp, vertical = 2.dp)
                                ) {
                                    Text("Hocayla", fontSize = 11.sp)
                                }
                                FilledTonalButton(
                                    onClick = { onNavigate(Screen.UnitDetail(course.id, unitName, "test")) },
                                    modifier = Modifier.weight(1f),
                                    contentPadding = androidx.compose.foundation.layout.PaddingValues(horizontal = 4.dp, vertical = 2.dp)
                                ) {
                                    Text("Soru Çöz", fontSize = 11.sp)
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

@Composable
fun AcademicAnalyticsScreen(
    repository: LgsRepository,
    onNavigate: (Screen) -> Unit,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    val dailyRecords by repository.dailyRecords.collectAsState()
    val unitProgressMap by repository.unitProgressMap.collectAsState()
    val trialExams by repository.trialExams.collectAsState()

    val totalMinutes = dailyRecords.values.sumOf { it.studyMinutes }
    val totalQuestions = dailyRecords.values.sumOf { it.questionsSolved }
    val totalCorrect = dailyRecords.values.sumOf { it.questionsCorrect }
    val accuracy = if (totalQuestions > 0) (totalCorrect * 100) / totalQuestions else 0
    val completedTopics = unitProgressMap.values.count { it.completed }
    val totalTopics = LgsCurriculum.courses.sumOf { it.units.size }
    val (xp, level) = repository.calculateXpAndLevel()
    val streak = repository.calculateStreak()

    LazyColumn(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp)
    ) {
        item {
            Row(verticalAlignment = Alignment.CenterVertically) {
                IconButton(onClick = onBack) {
                    Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Geri")
                }
                Text("📊 Akademik Analiz Merkezi", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
            }
        }

        item {
            Card(
                shape = RoundedCornerShape(16.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text("Genel Metrikler", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
                    Spacer(modifier = Modifier.height(10.dp))
                    MetricRow(label = "Tamamlanan Konular", value = "$completedTopics / $totalTopics")
                    MetricRow(label = "Toplam Çalışma Süresi", value = "$totalMinutes dakika (~${totalMinutes / 60} saat)")
                    MetricRow(label = "Çözülen Soru Sayısı", value = "$totalQuestions soru")
                    MetricRow(label = "Genel Doğruluk Oranı", value = "%$accuracy ($totalCorrect Doğru)")
                    MetricRow(label = "Aktif Çalışma Serisi", value = "$streak gün")
                    MetricRow(label = "Akademik Seviye & XP", value = "Seviye $level ($xp XP)")
                    MetricRow(label = "Kayıtlı Deneme Sınavları", value = "${trialExams.size} deneme")
                }
            }
        }

        item {
            Text("Ders Bazlı Başarı Dağılımı", style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
        }

        items(LgsCurriculum.courses) { course ->
            var qCount = 0
            var cCount = 0
            course.units.forEach { unit ->
                val p = unitProgressMap["${course.id}|$unit"]
                if (p != null) {
                    qCount += p.totalAnswers
                    cCount += p.correctAnswers
                }
            }
            val courseAcc = if (qCount > 0) (cCount * 100) / qCount else 0

            Card(
                shape = RoundedCornerShape(12.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
            ) {
                Column(modifier = Modifier.padding(14.dp)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text("${course.icon} ${course.name}", fontWeight = FontWeight.Bold)
                        Text(if (qCount > 0) "%$courseAcc ($cCount/$qCount)" else "Veri yok", fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                    }
                    Spacer(modifier = Modifier.height(6.dp))
                    LinearProgressIndicator(
                        progress = { (courseAcc / 100f).coerceIn(0f, 1f) },
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(6.dp)
                            .clip(RoundedCornerShape(3.dp)),
                        color = MaterialTheme.colorScheme.primary,
                        trackColor = MaterialTheme.colorScheme.surfaceVariant
                    )
                }
            }
        }
    }
}

